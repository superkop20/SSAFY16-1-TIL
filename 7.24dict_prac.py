# =============================================================
# [실습 2 해설] 딕셔너리의 키와 값 뒤집기
# - {1: 10} => {10: [1]} 로 뒤집기
#
# [왜 값이 리스트인가]
#    원래 딕셔너리에서 키는 중복될 수 없지만 값은 중복될 수 있음
#    => 뒤집으면 여러 키가 같은 자리로 몰릴 수 있으므로
#       모든 결과를 리스트에 담아 통일함
#       {1: 30, 4: 30}  =>  {30: [1, 4]}
#
# [실행 주의] 세 함수의 이름이 모두 dict_invert로 같습니다.
#    맨 아래 테스트가 호출하는 것은 '3번 defaultdict 버전'입니다.
#    1번, 2번을 확인하려면 아래쪽 함수를 주석 처리하고 실행하세요.
# =============================================================

# 딕셔너리를 입력받아 value와 key를 뒤집은 결과를 반환하는 함수 `dict_invert()`를 작성하기


# =============================================================
# [해설 1] [] 표기법 - 존재 여부를 직접 확인
# - 핵심 고민: 뒤집은 키가 새 딕셔너리에 이미 있는가?
#             없으면 => 리스트를 새로 만들어 넣기      [key]
#             있으면 => 기존 리스트에 이어 붙이기      .append(key)
# 
# - items()로 (키, 값)을 함께 꺼내 순회
# - 뒤집은 키(value)가 새 딕셔너리에 있는지에 따라 처리가 갈림
#     없으면 : 리스트를 새로 만들어 넣음  [key]
#     있으면 : 기존 리스트에 추가         .append(key)
# - 주의: [key] 처럼 대괄호로 감싸야 함
#         new_dict[value] = key 로 쓰면 리스트가 아닌 값이 들어가
#         나중에 append를 할 수 없게 됨
# =============================================================

# 1. [] 표기법을 사용한 방법
def dict_invert(input_dict):
    new_dict = {}
    for key, value in input_dict.items():
        # 딕셔너리 안에 없는 경우 -> key-value 값 생성
        if value not in new_dict:
            new_dict[value] = [key]
        # 딕셔너리 안에 있는 경우 -> value 리스트에 요소 하나 추가
        else:
            new_dict[value].append(key)
    return new_dict


# =============================================================
# [해설 2] get() - 리스트 덧셈으로 통합
# - 핵심 고민: 리스트끼리는 + 연산으로 이어붙일 수 있음
#             => 가져온 리스트에 [key]를 더해 다시 저장하면 끝
# 
# - get(value, [])는 "있으면 그 리스트, 없으면 빈 리스트"를 반환
# - 리스트 + 리스트는 이어붙인 새 리스트를 만듦
#     []      + [1] => [1]        (처음 등장)
#     [3]     + [4] => [3, 4]     (이미 있던 경우)
#   => 두 경우가 하나의 식으로 처리됨
# - append와의 차이: append는 원본을 바꾸고 None을 반환하지만,
#   +는 새 리스트를 반환하므로 이렇게 대입식에 쓸 수 있음
# =============================================================

# 2. get 메서드를 사용한 방법
def dict_invert(input_dict):
    new_dict = {}
    for key, value in input_dict.items():
        new_dict[value] = new_dict.get(value, []) + [key]
    return new_dict


